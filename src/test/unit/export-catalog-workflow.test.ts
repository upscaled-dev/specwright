import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import * as vscode from "vscode";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { exportScenariosCatalog, exportStepsCatalog } from "../../commands/export-catalogs";
import type { StepUsageIndex } from "../../providers/step-usage-index";
import { captureHandlers, makeContext } from "./helpers/command-manager-harness";

let root: string;
let files: string[];
let target: string;
let context: ReturnType<typeof makeContext>;

beforeEach(() => {
  root = fs.mkdtempSync(path.join(os.tmpdir(), "specwright-catalog-"));
  files = [path.join(root, "checkout.feature"), path.join(root, "profile.feature")];
  fs.writeFileSync(files[0]!, "Feature: Checkout\n  @smoke\n  Scenario: Pay by card\n    Given a basket\n");
  fs.writeFileSync(files[1]!, "Feature: Profile\n  @account\n  Scenario: Edit profile\n    Given a signed in user\n");
  target = path.join(root, "catalog.md");
  context = makeContext();
  vi.spyOn(context.discoveryManager, "discoverTestFiles").mockImplementation(() => Promise.resolve(files));
  vi.spyOn(vscode.workspace, "workspaceFolders", "get").mockReturnValue([
    { name: "shop", index: 0, uri: vscode.Uri.file(root) },
  ]);
  vi.spyOn(vscode.workspace, "getWorkspaceFolder").mockReturnValue({ name: "shop", index: 0, uri: vscode.Uri.file(root) });
  vi.spyOn(vscode.window, "showSaveDialog").mockResolvedValue(vscode.Uri.file(target));
  vi.spyOn(vscode.workspace, "openTextDocument").mockResolvedValue({ uri: vscode.Uri.file(target) } as vscode.TextDocument);
  vi.spyOn(vscode.window, "showTextDocument").mockResolvedValue({} as vscode.TextEditor);
});

afterEach(() => {
  vi.restoreAllMocks();
  fs.rmSync(root, { recursive: true, force: true });
});

function picks(...values: unknown[]): void {
  const pick = vi.spyOn(vscode.window, "showQuickPick");
  for (const value of values) { pick.mockResolvedValueOnce(value as never); }
}

function output(): string { return fs.readFileSync(target, "utf-8"); }

describe("catalog export workflow", () => {
  it.each([true, false])("writes and opens parsed scenarios, skipping unreadable files (workspace: %s)", async (workspace) => {
    if (!workspace) {
      vi.spyOn(vscode.workspace, "workspaceFolders", "get").mockReturnValue(undefined);
      vi.mocked(vscode.workspace.getWorkspaceFolder).mockReturnValue(undefined);
    }
    files.push(path.join(root, "missing.feature"));
    picks({ scope: "all" });
    await exportScenariosCatalog(context);
    expect(output()).toContain("Pay by card");
    expect(output()).toContain("Edit profile");
    expect(output()).toContain("Generated by Specwright");
    expect(vscode.workspace.openTextDocument).toHaveBeenCalledWith(expect.objectContaining({ fsPath: target }));
    expect(vscode.window.showTextDocument).toHaveBeenCalledWith(expect.objectContaining({ uri: expect.objectContaining({ fsPath: target }) }));
    expect(vscode.window.showSaveDialog).toHaveBeenCalledWith(expect.objectContaining({
      defaultUri: expect.objectContaining({ fsPath: workspace ? path.join(root, "scenarios.md") : vscode.Uri.file("scenarios.md").fsPath }),
    }));
  });

  it.each([
    [[{ label: "@smoke", custom: false }], undefined],
    [[{ label: "Custom", custom: true }], "  @smoke,  "],
  ])("exports only matching scenarios for a chosen or typed tag", async (tags, input) => {
    picks({ scope: "tag" }, tags);
    vi.spyOn(vscode.window, "showInputBox").mockResolvedValue(input);
    await exportScenariosCatalog(context);
    expect(output()).toContain("Pay by card");
    expect(output()).not.toContain("Edit profile");
    expect(output()).toContain("1 of 2 features included");
  });

  it("exports only selected feature files", async () => {
    const pick = vi.spyOn(vscode.window, "showQuickPick");
    pick.mockResolvedValueOnce({ scope: "selected" } as never);
    pick.mockImplementationOnce(async (items) => [(items as vscode.QuickPickItem[])[1]] as never);
    await exportScenariosCatalog(context);
    expect(output()).toContain("Edit profile");
    expect(output()).not.toContain("Pay by card");
    expect(output()).toContain("Selected features: 1 of 2 included.");
  });

  it.each([
    [undefined], [{ scope: "tag" }, undefined], [{ scope: "tag" }, []],
    [{ scope: "tag" }, [{ custom: true }]],
    [{ scope: "selected" }, undefined], [{ scope: "selected" }, []],
  ])("does not prompt to save after a cancelled or empty scope: %j", async (...selections) => {
    picks(...selections);
    vi.spyOn(vscode.window, "showInputBox").mockResolvedValue(undefined);
    await exportScenariosCatalog(context);
    expect(vscode.window.showSaveDialog).not.toHaveBeenCalled();
    expect(fs.existsSync(target)).toBe(false);
  });

  it("ignores a custom tag selection containing only separators", async () => {
    picks({ scope: "tag" }, [{ custom: true }]);
    vi.spyOn(vscode.window, "showInputBox").mockResolvedValue(" ,  ");
    await exportScenariosCatalog(context);
    expect(vscode.window.showSaveDialog).not.toHaveBeenCalled();
  });

  it("informs the user when discovery finds no features", async () => {
    files = [];
    const message = vi.spyOn(vscode.window, "showInformationMessage");
    await exportScenariosCatalog(context);
    expect(message).toHaveBeenCalledWith("No feature files found to export.");
    expect(vscode.window.showSaveDialog).not.toHaveBeenCalled();
  });

  it("keeps the destination unchanged when the save dialog is cancelled", async () => {
    fs.writeFileSync(target, "existing catalog");
    picks({ scope: "all" });
    vi.mocked(vscode.window.showSaveDialog).mockResolvedValue(undefined);
    await exportScenariosCatalog(context);
    expect(output()).toBe("existing catalog");
    expect(vscode.workspace.openTextDocument).not.toHaveBeenCalled();
  });

  it("keeps separate folder headings in a multi-root scenario catalog", async () => {
    vi.mocked(vscode.workspace.getWorkspaceFolder).mockImplementation((uri) => ({
      name: uri.fsPath === files[0] ? "checkout" : "accounts", index: 0, uri: vscode.Uri.file(root),
    }));
    vi.spyOn(vscode.workspace, "workspaceFolders", "get").mockReturnValue([
      { name: "checkout", index: 0, uri: vscode.Uri.file(root) },
      { name: "accounts", index: 1, uri: vscode.Uri.file(root) },
    ]);
    picks({ scope: "all" });
    await exportScenariosCatalog(context);
    expect(output()).toContain("checkout");
    expect(output()).toContain("accounts");
    expect(output()).toContain("Pay by card");
    expect(output()).toContain("Edit profile");
  });

  it.each(["direct", "registered"])("exports step definitions and usage counts without an open workspace via %s", async (route) => {
    vi.spyOn(vscode.workspace, "workspaceFolders", "get").mockReturnValue(undefined);
    vi.mocked(vscode.workspace.getWorkspaceFolder).mockReturnValue(undefined);
    const definition = { line: 2, regex: /a basket/, pattern: "a basket", isRegex: false,
      keyword: "Given" as const, filePath: path.join(root, "checkout.steps.ts") };
    const index = { getAllUsages: async () => new Map([[definition, [
      { featurePath: files[0]!, line: 3, stepText: "a basket", keyword: "Given" as const },
    ]]]) } as unknown as StepUsageIndex;
    if (route === "direct") {await exportStepsCatalog(index);}
    else {
      const handlers = captureHandlers(context, (manager) => manager.setUsageIndexHost({
        getUsageIndex: () => index,
        projectCapabilities: async () => ({
          workspace: false, featureFiles: files.length, stepDefinitions: 1, stepDefinitionPaths: ["**/*.steps.ts"],
        }),
      }));
      await handlers.get("playwrightBddRunner.exportSteps")!();
    }
    expect(output()).toContain("a basket");
    expect(output()).toContain("checkout.steps.ts");
    expect(vscode.window.showSaveDialog).toHaveBeenCalledWith(expect.objectContaining({ defaultUri: expect.objectContaining({ fsPath: "steps.md" }) }));
  });
});
